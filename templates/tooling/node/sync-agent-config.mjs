#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { isActiveLayerName, layerSlug, parseArgs, projectRoot, toLf, walkFiles, writeText } from './lib/util.mjs';

/**
 * Synchronizuje agentní konfiguraci vrstev z src/<Layer>/.cursor/ do root .cursor/.
 *
 *   src/<Layer>/.cursor/rules/*.mdc      -> .cursor/rules/generated/<slug>/*.mdc
 *   src/<Layer>/.cursor/agents/*.md      -> .cursor/agents/<slug>-*.md
 *   src/<Layer>/.cursor/skills/<x>/...   -> .cursor/skills/<slug>-<x>/...
 *
 * Pravidlům se přepíše globs na ["src/<Layer>/**"] a přidá se hlavička GENERATED.
 * Generované soubory jsou evidovány v .cursor/.generated-manifest.json.
 *
 * Skript zapisuje výhradně do root .cursor/ a jen u souborů vedených v manifestu.
 * Zdroje v src/<Layer>/.cursor/ nikdy nemění.
 *
 * Použití:
 *   node scripts/sync-agent-config.mjs
 *   node scripts/sync-agent-config.mjs --check
 */
const args = parseArgs(process.argv.slice(2));
const checkOnly = Boolean(args.check);

const srcRoot = path.join(projectRoot, 'src');
const cursorRoot = path.join(projectRoot, '.cursor');
const manifestPath = path.join(cursorRoot, '.generated-manifest.json');
const marker = 'GENERATED by scripts/sync-agent-config.mjs - do not edit';

function readText(filePath) {
  return toLf(fs.readFileSync(filePath, 'utf8'));
}

function frontmatterValue(text, field) {
  const match = /^---\s*\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return null;

  const line = new RegExp(`^\\s*${field}\\s*:\\s*(.+?)\\s*$`, 'm').exec(match[1]);
  return line ? line[1].trim().replace(/^"|"$/g, '').replace(/^'|'$/g, '') : null;
}

function markdownBody(text) {
  const match = /^---\s*\r?\n[\s\S]*?\r?\n---\s*\r?\n?/.exec(text);
  return match ? text.slice(match[0].length) : text;
}

function yamlSafe(value) {
  return String(value).replace(/"/g, "'").trim();
}

function listLayerDirs() {
  if (!fs.existsSync(srcRoot)) return [];

  return fs
    .readdirSync(srcRoot, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        isActiveLayerName(entry.name) &&
        fs.existsSync(path.join(srcRoot, entry.name, '.cursor')),
    )
    .map((entry) => entry.name)
    .sort();
}

const expected = new Map();

for (const layer of listLayerDirs()) {
  const slug = layerSlug(layer);
  const cursorDir = path.join(srcRoot, layer, '.cursor');

  const rulesDir = path.join(cursorDir, 'rules');
  if (fs.existsSync(rulesDir)) {
    for (const file of fs.readdirSync(rulesDir).filter((name) => name.endsWith('.mdc'))) {
      const text = readText(path.join(rulesDir, file));
      const description = yamlSafe(frontmatterValue(text, 'description') ?? `${layer} standards`);
      const body = toLf(markdownBody(text)).trim();

      const content =
        `---\n` +
        `description: "[${layer}] ${description}"\n` +
        `globs: ["src/${layer}/**"]\n` +
        `alwaysApply: false\n` +
        `---\n` +
        `<!-- ${marker} | source: src/${layer}/.cursor/rules/${file} -->\n\n` +
        `${body}\n`;

      expected.set(`.cursor/rules/generated/${slug}/${file}`, toLf(content));
    }
  }

  const agentsDir = path.join(cursorDir, 'agents');
  if (fs.existsSync(agentsDir)) {
    for (const file of fs.readdirSync(agentsDir).filter((name) => name.endsWith('.md'))) {
      const text = readText(path.join(agentsDir, file));
      let name = frontmatterValue(text, 'name') ?? file.replace(/\.md$/, '');

      if (!(name === slug || name.startsWith(`${slug}-`))) {
        name = `${slug}-${name}`;
      }

      const description = yamlSafe(frontmatterValue(text, 'description') ?? `${layer} agent`);
      const model = frontmatterValue(text, 'model') ?? 'inherit';
      const readonly = frontmatterValue(text, 'readonly') ?? 'false';
      const isBackground = frontmatterValue(text, 'is_background') ?? 'false';
      const body = toLf(markdownBody(text)).trim();

      const content =
        `---\n` +
        `name: ${name}\n` +
        `description: "[${layer}] ${description}"\n` +
        `model: ${model}\n` +
        `readonly: ${readonly}\n` +
        `is_background: ${isBackground}\n` +
        `---\n\n` +
        `${body}\n`;

      expected.set(`.cursor/agents/${slug}-${file}`, toLf(content));
    }
  }

  const skillsDir = path.join(cursorDir, 'skills');
  if (fs.existsSync(skillsDir)) {
    for (const skillName of fs
      .readdirSync(skillsDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)) {
      const skillDir = path.join(skillsDir, skillName);
      const targetSkill = `${slug}-${skillName}`;

      for (const relative of walkFiles(skillDir)) {
        const target = `.cursor/skills/${targetSkill}/${relative}`;

        if (path.basename(relative) === 'SKILL.md') {
          const text = readText(path.join(skillDir, relative));
          let name = frontmatterValue(text, 'name') ?? skillName;

          if (!(name === slug || name.startsWith(`${slug}-`))) {
            name = `${slug}-${name}`;
          }

          const description = yamlSafe(frontmatterValue(text, 'description') ?? `${layer} skill`);
          const body = toLf(markdownBody(text)).trim();

          const content =
            `---\n` +
            `name: ${name}\n` +
            `description: "[${layer}] ${description}"\n` +
            `disable-model-invocation: true\n` +
            `---\n\n` +
            `${body}\n`;

          expected.set(target, toLf(content));
        } else {
          expected.set(target, readText(path.join(skillDir, relative)));
        }
      }
    }
  }
}

let previous = [];
if (fs.existsSync(manifestPath)) {
  try {
    const parsed = JSON.parse(readText(manifestPath));
    previous = Array.isArray(parsed) ? parsed.filter((item) => typeof item === 'string') : [];
  } catch {
    previous = [];
  }
}

const changed = [];
const missing = [];

for (const [relative, content] of [...expected.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const full = path.join(projectRoot, relative);

  if (!fs.existsSync(full)) {
    missing.push(relative);
    continue;
  }

  if (readText(full) !== content) changed.push(relative);
}

const orphans = previous.filter((relative) => !expected.has(relative));

if (checkOnly) {
  const problems = [];

  if (missing.length > 0) {
    problems.push(`Chybějící generované soubory (${missing.length}):`, ...missing.map((p) => `  - ${p}`));
  }

  if (changed.length > 0) {
    problems.push(`Zastaralé generované soubory (${changed.length}):`, ...changed.map((p) => `  - ${p}`));
  }

  if (orphans.length > 0) {
    problems.push(`Osiřelé generované soubory (${orphans.length}):`, ...orphans.map((p) => `  - ${p}`));
  }

  if (problems.length > 0) {
    console.error('Agentní konfigurace NENÍ v souladu se zdroji ve vrstvách.');
    console.error('');
    for (const line of problems) console.error(line);
    console.error('');
    console.error('Spusť: node scripts/sync-agent-config.mjs');
    process.exit(1);
  }

  console.log(`Agentní konfigurace je v souladu (${expected.size} generovaných souborů).`);
  process.exit(0);
}

for (const relative of changed) console.log(`  update ${relative}`);
for (const relative of missing) console.log(`  create ${relative}`);

for (const [relative, content] of [...changed.map((r) => [r, expected.get(r)]), ...missing.map((r) => [r, expected.get(r)])]) {
  writeText(path.join(projectRoot, relative), content);
}

for (const relative of orphans) {
  const full = path.join(projectRoot, relative);
  if (fs.existsSync(full)) {
    fs.rmSync(full, { force: true });
    console.log(`  remove ${relative}`);
  }
}

for (const base of [path.join(cursorRoot, 'rules/generated'), path.join(cursorRoot, 'skills')]) {
  if (!fs.existsSync(base)) continue;

  const dirs = walkDirectories(base).sort((a, b) => b.length - a.length);
  for (const dir of dirs) {
    const entries = walkFiles(dir);
    if (entries.length === 0) {
      fs.rmSync(dir, { recursive: true, force: true });
      console.log(`  remove ${path.basename(dir)}/ (prázdný)`);
    }
  }
}

function walkDirectories(dir) {
  const result = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        const full = path.join(current, entry.name);
        result.push(full);
        stack.push(full);
      }
    }
  }
  return result;
}

const manifestContent = `${JSON.stringify([...expected.keys()].sort(), null, 2)}\n`;
const existingManifest = fs.existsSync(manifestPath) ? readText(manifestPath) : null;

if (existingManifest !== manifestContent) {
  writeText(manifestPath, manifestContent);
}

console.log('');
console.log(
  `Synchronizace dokončena: ${listLayerDirs().length} vrstev, ${expected.size} generovaných souborů.`,
);
console.log('Zdroj pravdy: src/<Layer>/.cursor/ | Generováno: .cursor/ (needitovat)');
